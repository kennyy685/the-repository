/* Route test + baker + proof pictures.
   node dev/route-test.mjs          builds the route from data/nl.js, checks it, BAKES it into js/lib/route.js
                                    (window.ROUTE_BAKED at the bottom), reloads it in Chromium to prove the baked path
                                    works with no computing, and renders shots/route-overview.png (+ -fremont, -columbus).
   node dev/route-test.mjs --no-bake  same checks, leaves route.js alone. */
import fs from 'fs';
import vm from 'vm';
import path from 'path';
import { fileURLToPath } from 'url';
import { createRequire } from 'module';
import { execSync } from 'child_process';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const NLJS = path.join(ROOT, 'data/nl.js'), RJS = path.join(ROOT, 'js/lib/route.js'), SHOTS = path.join(ROOT, 'shots');
const MARK = '/* ==== ROUTE_BAKED: generated by dev/route-test.mjs, do not hand-edit below this line ==== */';
const noBake = process.argv.includes('--no-bake');

let fails = 0;
const ok = (c, m) => { console.log((c ? '  ok   ' : '  FAIL ') + m); if (!c) fails++; };

function load(withBaked) {
  const c = { window: {} }; c.globalThis = c;
  vm.runInNewContext(fs.readFileSync(NLJS, 'utf8'), c);
  let src = fs.readFileSync(RJS, 'utf8');
  if (!withBaked) src = src.split(MARK)[0];
  vm.runInNewContext(src, c);
  return c.window;
}

/* ---------- 1. build from the real lines ---------- */
const W = load(false), NL = W.NL, Route = W.Route;
let t0 = Date.now();
const route = Route.build(NL);
const buildMs = Date.now() - t0;
console.log(`\nRoute HQ ${NL.hq} -> park ${NL.walk.park}  (built in ${buildMs} ms; snaps ${route.stats.snaps}, highway crossings joined ${route.stats.crossings}, bridges ${route.stats.bridges})`);
console.log(`  ${route.miles} mi, ${route.minutes} min, ${route.line.length} vertices`);
route.legs.forEach(l => console.log(`  leg  ${l.name.padEnd(16)} ${String(l.miles).padStart(6)} mi  ${String(l.minutes).padStart(5)} min  mile ${l.fromMile}-${l.toMile}  via ${l.via.join(', ') || '-'}`));
console.log('  stops ' + route.stops.map(s => `${s.name}@${s.mile}`).join('  '));

/* ---------- 2. checks ---------- */
console.log('\nChecks');
const { collect, KX, KY, LON0, LAT0 } = Route._;
const first = route.line[0], last = route.line[route.line.length - 1];
ok(first[0] === NL.hq[0] && first[1] === NL.hq[1], 'line starts exactly at NL.hq');
ok(last[0] === NL.walk.park[0] && last[1] === NL.walk.park[1], 'line ends exactly at NL.walk.park');
ok(route.miles >= 43 && route.miles <= 52, `miles ${route.miles} within 43-52 (straight line is ${(Math.hypot((NL.hq[0] - NL.walk.park[0]) * KX, (NL.hq[1] - NL.walk.park[1]) * KY) / 1609.344).toFixed(1)} mi, engine dist_mi ${NL.pick.dist_mi})`);
ok(route.minutes >= 40 && route.minutes <= 70, `minutes ${route.minutes} within 40-70`);
const us30 = route.legs.filter(l => l.name === 'US-30').reduce((a, l) => a + l.miles, 0);
ok(us30 / route.miles > 0.75, `US-30 carries ${(us30 / route.miles * 100).toFixed(0)}% of the drive`);
ok(route.stops.map(s => s.name).join() === 'Fremont,North Bend,Schuyler,Columbus', 'passes Fremont, North Bend, Schuyler, Columbus in order');
ok(Math.abs(route.legs.reduce((a, l) => a + l.miles, 0) - route.miles) < 0.1 && route.legs.every((l, i) => i === 0 || Math.abs(l.fromMile - route.legs[i - 1].toMile) < 0.11), 'legs are contiguous and add up to the total');
ok(Math.abs(route.legs.reduce((a, l) => a + l.minutes, 0) - route.minutes) < 1, 'leg minutes add up to the total');
ok(route.cum.every((v, i) => i === 0 || v >= route.cum[i - 1]) && Math.abs(route.cum[route.cum.length - 1] - route.miles) < 0.1, 'cum[] is monotonic and ends at miles');

/* every route vertex sits on a real source line (the two spur ends excepted) */
{
  const lines = collect(NL).map(l => l.pts);
  function dist(x, y) {
    let best = 1e9;
    for (const pts of lines) for (let i = 0; i + 1 < pts.length; i++) {
      const ax = pts[i][0], ay = pts[i][1], dx = pts[i + 1][0] - ax, dy = pts[i + 1][1] - ay, l2 = dx * dx + dy * dy;
      let t = l2 ? ((x - ax) * dx + (y - ay) * dy) / l2 : 0; t = t < 0 ? 0 : t > 1 ? 1 : t;
      const d = Math.hypot(x - ax - t * dx, y - ay - t * dy); if (d < best) best = d;
    }
    return best;
  }
  let worst = 0, worstAt = null;
  route.line.forEach((q, i) => {
    if (i === 0 || i === route.line.length - 1) return;
    const d = dist((q[0] - LON0) * KX, (q[1] - LAT0) * KY);
    if (d > worst) { worst = d; worstAt = q; }
  });
  const spur0 = dist((first[0] - LON0) * KX, (first[1] - LAT0) * KY), spur1 = dist((last[0] - LON0) * KX, (last[1] - LAT0) * KY);
  ok(worst <= 45, `every inner vertex is on a real road line (worst ${worst.toFixed(1)} m${worst > 45 ? ' at ' + worstAt : ''}); HQ is ${spur0.toFixed(0)} m and the park ${spur1.toFixed(0)} m from a road line`);
}

/* Route.at: ends, monotonic miles, sane headings */
{
  const a0 = Route.at(route, 0), a1 = Route.at(route, 1), am = Route.at(route, 0.5);
  ok(a0.p[0] === first[0] && a0.p[1] === first[1] && a0.mile === 0, 'at(0) = HQ, mile 0');
  ok(Math.abs(a1.p[0] - last[0]) < 1e-9 && Math.abs(a1.mile - route.cum[route.cum.length - 1]) < 1e-9, 'at(1) = parking spot, last mile');
  ok(Math.abs(am.mile - route.cum[route.cum.length - 1] / 2) < 1e-9, 'at(0.5) is at half the distance');
  let prev = -1, mono = true, hOk = true;
  for (let i = 0; i <= 200; i++) { const r = Route.at(route, i / 200); if (r.mile < prev) mono = false; prev = r.mile; if (!(r.heading >= 0 && r.heading < 360)) hOk = false; }
  ok(mono && hOk, 'at(f) miles never go backwards; heading always 0-360');
  const hUS30 = Route.at(route, 0.5).heading;
  ok(hUS30 > 240 && hUS30 < 300, `mid-drive heading ${hUS30} deg is west (US-30 westbound)`);
  ok(Route.at(route, -1).mile === 0 && Route.at(route, 2).mile === route.cum[route.cum.length - 1], 'f is clamped to 0..1');
  const tm = Route.atTime(route, 0.5), mm = Route.minutesAt(route, tm.mile / route.cum[route.cum.length - 1]);
  ok(Math.abs(mm - route.minutes / 2) < 1.5, `atTime(0.5) is half the drive TIME (${mm.toFixed(1)} of ${route.minutes} min, at mile ${tm.mile.toFixed(1)})`);
  const tr = Route.trail(route, 0.5);
  ok(tr.length >= 2 && tr[0][0] === first[0], `trail(0.5) has ${tr.length} points from HQ to the car`);
}

/* ---------- 3. bake ---------- */
const baked = Route.bake(route);
const bakedJs = 'window.ROUTE_BAKED = {\n' + Object.keys(baked).map(k => `  ${JSON.stringify(k)}: ${JSON.stringify(baked[k])}`).join(',\n') + '\n};\n';
if (!noBake) {
  const src = fs.readFileSync(RJS, 'utf8').split(MARK)[0];
  fs.writeFileSync(RJS, src + MARK + '\n' + bakedJs);
  console.log(`\nBaked -> js/lib/route.js (+${bakedJs.length} bytes, ${baked.line.length} vertices)`);
}
{
  const W2 = load(true);
  const r2 = W2.Route.load(W2.NL);   /* takes the baked path when present */
  const same = JSON.stringify(r2.line) === JSON.stringify(route.line);
  ok(noBake || same, noBake ? 'no-bake run: baked check skipped' : 'Route.load() with the baked block gives the same line as build() (no computing at load)');
  const hy = W2.Route.at(r2, 0.37), bu = Route.at(route, 0.37);
  ok(noBake || (Math.abs(hy.p[0] - bu.p[0]) < 1e-6 && Math.abs(hy.mile - bu.mile) < 0.01), 'baked route animates identically (at(0.37))');
}

/* ---------- 4. pictures (real Chromium, real script tags: proves route.js runs in a page) ---------- */
function loadPlaywright() {
  try { return createRequire(import.meta.url)('playwright'); } catch (e) {
    return createRequire(path.join(execSync('npm root -g').toString().trim(), 'noop.js'))('playwright');
  }
}
const { chromium } = loadPlaywright();
const browser = await chromium.launch();
async function shot(file, o) {
  const page = await browser.newPage({ viewport: { width: o.w, height: o.h }, deviceScaleFactor: 2 });
  const errs = []; page.on('pageerror', e => errs.push(e.message)); page.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
  await page.setContent('<!doctype html><meta charset=utf-8><body style="margin:0;background:#101318"><canvas id=c width=' + o.w * 2 + ' height=' + o.h * 2 + ' style="width:' + o.w + 'px;height:' + o.h + 'px"></canvas></body>');
  await page.addScriptTag({ content: fs.readFileSync(NLJS, 'utf8') });
  await page.addScriptTag({ content: fs.readFileSync(RJS, 'utf8') });
  const info = await page.evaluate((o) => {
    const NL = window.NL, R = Route.load(NL), cv = document.getElementById('c'), g = cv.getContext('2d');
    g.scale(2, 2);
    const W = o.w, H = o.h, [x0, y0, x1, y1] = o.box, cosl = Math.cos(41.44 * Math.PI / 180);
    /* fit box into canvas keeping true aspect */
    const sx = W / ((x1 - x0) * cosl), sy = H / (y1 - y0), s = Math.min(sx, sy);
    const ox = (W - (x1 - x0) * cosl * s) / 2, oy = (H - (y1 - y0) * s) / 2;
    const X = q => ox + (q[0] - x0) * cosl * s, Y = q => H - oy - (q[1] - y0) * s;
    function path(p, col, w, dash) { g.beginPath(); p.forEach((q, i) => i ? g.lineTo(X(q), Y(q)) : g.moveTo(X(q), Y(q))); g.strokeStyle = col; g.lineWidth = w; g.setLineDash(dash || []); g.stroke(); g.setLineDash([]); }
    g.lineJoin = g.lineCap = 'round';
    for (const b of NL.base) if (b.k === 'county') path(b.p, '#22272f', 1, [3, 4]);
    for (const b of NL.base) if (b.k === 'town') { g.beginPath(); b.p.forEach((q, i) => i ? g.lineTo(X(q), Y(q)) : g.moveTo(X(q), Y(q))); g.fillStyle = '#1c2029'; g.fill(); }
    for (const b of NL.base) if (b.k === 'water' || b.k === 'stream') path(b.p, '#1c3550', b.k === 'water' ? 1 : 0.8);
    for (const b of NL.base) if (b.k === 'rail') path(b.p, '#3a3f4b', 1, [5, 3]);
    for (const st of NL.fremont.concat(NL.columbus)) path(st.p, ['#5a6270', '#4a515d', '#343a45', '#2a2f39'][st.c], st.c < 2 ? 1.6 : 0.9);
    for (const a of NL.arts) path(a.p, a.c === 0 ? '#3f6aa0' : '#33507a', 1.2);
    for (const b of NL.base) if (b.k === 'hwy') path(b.p, '#a9772a', 2.2);
    /* the route: soft glow, then the line */
    g.save(); g.shadowColor = 'rgba(255,106,26,.85)'; g.shadowBlur = 12; path(R.line, '#ff6a1a', o.lw || 4); g.restore();
    path(R.line, '#ffb27a', 1);
    /* mile ticks */
    if (o.ticks) for (let m = 10; m < R.miles; m += 10) { const a = Route.atMile(R, m); g.fillStyle = '#fff'; g.beginPath(); g.arc(X(a.p), Y(a.p), 3, 0, 7); g.fill(); g.font = '11px system-ui'; g.fillText(m + ' mi', X(a.p) - 12, Y(a.p) - 9); }
    /* cars at quarters, heading arrows */
    if (o.cars) [0.12, 0.3, 0.5, 0.7, 0.9].forEach(f => { const a = Route.at(R, f), h = a.heading * Math.PI / 180, x = X(a.p), y = Y(a.p);
      g.save(); g.translate(x, y); g.rotate(h); g.fillStyle = '#5be0a0'; g.strokeStyle = '#0b3a26'; g.beginPath(); g.moveTo(0, -8); g.lineTo(5, 6); g.lineTo(0, 3); g.lineTo(-5, 6); g.closePath(); g.fill(); g.stroke(); g.restore();
      g.fillStyle = '#5be0a0'; g.font = '11px system-ui'; g.fillText(Math.round(a.heading) + '°', x + 8, y + 16); });
    /* ends + towns */
    g.font = '600 13px system-ui';
    for (const [q, lab, dx] of [[NL.hq, 'HMP base', 10], [NL.walk.park, 'Pick: 22 St & 40th Ave', 10]]) {
      g.fillStyle = '#5be0a0'; g.beginPath(); g.arc(X(q), Y(q), 6, 0, 7); g.fill(); g.strokeStyle = '#0b3a26'; g.lineWidth = 2; g.stroke();
      g.fillStyle = '#e8ecf2'; g.textAlign = dx < 0 ? 'right' : 'left'; g.fillText(lab, X(q) + dx, Y(q) - 12); g.textAlign = 'left';
    }
    if (o.towns) R.stops.forEach(s => { const p = NL.places[s.name]; g.fillStyle = '#9aa4b5'; g.font = '12px system-ui'; g.beginPath(); g.arc(X(p), Y(p), 2.5, 0, 7); g.fill(); g.fillText(s.name, X(p) + 6, Y(p) + 14); });
    /* header */
    g.fillStyle = 'rgba(16,19,24,.85)'; g.fillRect(12, 12, o.hw || 470, 20 + 16 * (R.legs.length + 1)); g.fillStyle = '#e8ecf2'; g.font = '600 14px system-ui';
    g.fillText(`${o.title || 'Route'}: ${R.miles} mi, ${R.minutes} min`, 24, 34);
    g.font = '12px system-ui'; g.fillStyle = '#b6bfce';
    R.legs.forEach((l, i) => g.fillText(`${l.name}  ${l.miles} mi  ${l.minutes} min` + (l.via.length ? '  via ' + l.via.join(', ') : ''), 24, 54 + i * 16));
    return { miles: R.miles, minutes: R.minutes, baked: !!window.ROUTE_BAKED };
  }, o);
  await page.screenshot({ path: path.join(SHOTS, file) });
  await page.close();
  console.log(`  shot ${file}  (page used ${info.baked ? 'baked' : 'computed'} route: ${info.miles} mi ${info.minutes} min)` + (errs.length ? '  ERRORS ' + errs.join(' | ') : ''));
  ok(errs.length === 0, `${file}: no page errors`);
}
fs.mkdirSync(SHOTS, { recursive: true });
console.log('\nPictures');
await shot('route-overview.png', { w: 1600, h: 470, box: [-97.53, 41.37, -96.38, 41.52], title: 'Fremont to Columbus', ticks: true, cars: true, towns: true, lw: 3.5 });
await shot('route-fremont.png', { w: 1000, h: 760, box: [-96.56, 41.42, -96.44, 41.49], title: 'Leaving Fremont', lw: 4, hw: 330 });
await shot('route-columbus.png', { w: 1000, h: 760, box: [-97.41, 41.415, -97.29, 41.46], title: 'Arriving in Columbus', lw: 4, hw: 330 });
await browser.close();

console.log(fails ? `\n${fails} check(s) FAILED` : '\nAll checks passed');
process.exit(fails ? 1 : 0);
